# WHO 数据覆盖的最大月龄
WHO_MAX_MONTH: int = 24

# 性别 -> 数据表映射（Baby.gender 实际取值为 "male"/"female"）
_GENDER_TABLES: dict[str, dict[str, dict[int, tuple[float, float, float, float, float]]]] = {
    "male": {"weight": WHO_WEIGHT_BOYS, "height": WHO_LENGTH_BOYS},
    "female": {"weight": WHO_WEIGHT_GIRLS, "height": WHO_LENGTH_GIRLS},
}


def _to_points(table: dict[int, tuple[float, float, float, float, float]], max_month: int) -> list[dict]:
    """将分位数据表转换为按月龄升序的点列表。

    @param table: 分位数据表 {月龄: (p3, p15, p50, p85, p97)}
    @param max_month: 最大月龄（含），只输出 0..max_month
    @return: [{"month": 月龄, "p3": ..., "p15": ..., "p50": ..., "p85": ..., "p97": ...}, ...]
    """
    return [
        {"month": m, "p3": row[0], "p15": row[1], "p50": row[2], "p85": row[3], "p97": row[4]}
        for m, row in sorted(table.items())
        if m <= max_month
    ]


def get_who_reference(gender: str | None, max_month: int = WHO_MAX_MONTH) -> dict:
    """获取 WHO 2006 生长标准参考线数据。

    @param gender: 宝宝性别（"male"/"female"）；未知或空值时按男孩表处理
    @param max_month: 最大月龄（含），超出 WHO 数据范围（>24）时自动截断到 24
    @return: {"height": [分位点列表], "weight": [分位点列表]}，
             每个点形如 {"month", "p3", "p15", "p50", "p85", "p97"}
    """
    tables = _GENDER_TABLES["male"] if gender not in _GENDER_TABLES else _GENDER_TABLES[gender]
    capped = min(max_month, WHO_MAX_MONTH)
    return {
        "height": _to_points(tables["height"], capped),
        "weight": _to_points(tables["weight"], capped),
    }
